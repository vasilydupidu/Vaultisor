// Чистая логика контракта сохранения поля записи: секрет не перезаписывается
// без явного нового значения. Вынесена для юнит-тестов.

export interface DraftFieldLike {
  /** id существующего поля (undefined — новое поле). */
  id?: string;
  /** Текущее значение в редакторе. */
  value: string | null;
  /** Значение, загруженное при открытии (undefined — поле не подгружалось). */
  original?: string;
}

/**
 * Значение поля для отправки на backend.
 *
 * Контракт backend: `null` = «не менять» (blob поля остаётся прежним), строка =
 * записать новое значение. Ключевые инварианты:
 *  - Существующее поле, чьё значение не изменилось относительно original (в т.ч.
 *    неподгруженное: value="" и original=undefined → оба ""), уходит как null —
 *    секрет НЕ перезаписывается.
 *  - Изменённое существующее и любое новое поле уходят строкой.
 */
export function fieldSaveValue(f: DraftFieldLike): string | null {
  if (f.id && (f.value ?? "") === (f.original ?? "")) return null;
  return f.value ?? "";
}
